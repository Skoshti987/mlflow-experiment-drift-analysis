"""
Data Drift Detection Module Using Two-Sample Kolmogorov-Smirnov Test.

Evaluates statistical distribution shifts between baseline reference data and
current/incoming data, generates reports (CSV, JSON), and produces visualizations.
"""

from typing import Dict, Any, List
from pathlib import Path
import json
import numpy as np
import pandas as pd
from scipy.stats import ks_2samp
import matplotlib.pyplot as plt


def compute_kolmogorov_smirnov_drift(
    reference_df: pd.DataFrame,
    current_df: pd.DataFrame,
    alpha: float = 0.05
) -> pd.DataFrame:
    """
    Perform two-sample Kolmogorov-Smirnov (KS) test for each numerical feature.

    Statistical Hypotheses:
        Null Hypothesis (H0): Both reference and current samples are drawn from the same continuous distribution.
        Alternative Hypothesis (H1): Reference and current samples are drawn from different distributions.

    A p-value < alpha (0.05) rejects H0 and indicates statistically significant evidence of data drift.
    Note: Statistical data drift does NOT inherently prove model performance degradation (concept drift).

    Args:
        reference_df: Baseline reference feature DataFrame.
        current_df: Current/monitoring feature DataFrame.
        alpha: Significance threshold (default: 0.05).

    Returns:
        pd.DataFrame containing feature, ks_statistic, p_value, alpha_threshold, and drift_detected.
    """
    if reference_df.empty or current_df.empty:
        raise ValueError("Cannot perform drift analysis on empty DataFrames.")

    if not (0 < alpha < 1):
        raise ValueError(f"Significance threshold alpha must be between 0 and 1. Got: {alpha}")

    # Ensure common feature columns
    common_features = [col for col in reference_df.columns if col in current_df.columns]
    if not common_features:
        raise ValueError("No common feature columns found between reference and current data.")

    results: List[Dict[str, Any]] = []

    for feature in common_features:
        ref_series = reference_df[feature].dropna()
        curr_series = current_df[feature].dropna()

        if len(ref_series) == 0 or len(curr_series) == 0:
            raise ValueError(f"Feature '{feature}' contains only null values or is empty.")

        # Check for constant variance degenerate case
        if ref_series.nunique() <= 1 and curr_series.nunique() <= 1 and (ref_series.iloc[0] == curr_series.iloc[0]):
            ks_stat = 0.0
            p_val = 1.0
        else:
            ks_res = ks_2samp(ref_series, curr_series)
            ks_stat = float(ks_res.statistic)
            p_val = float(ks_res.pvalue)

        drift_detected = bool(p_val < alpha)

        results.append({
            "feature": feature,
            "ks_statistic": round(ks_stat, 5),
            "p_value": round(p_val, 6),
            "alpha_threshold": alpha,
            "drift_detected": drift_detected,
            "drift_status": "Drift Detected" if drift_detected else "No Drift"
        })

    return pd.DataFrame(results)


def save_drift_reports(
    drift_df: pd.DataFrame,
    scenario_metadata: Dict[str, Any],
    output_dir: str = "reports"
) -> Dict[str, str]:
    """
    Export drift analysis findings to CSV and JSON summary files.

    Args:
        drift_df: DataFrame generated by compute_kolmogorov_smirnov_drift.
        scenario_metadata: Metadata describing test configuration and environment.
        output_dir: Target directory path.

    Returns:
        Dictionary of created file paths.
    """
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    csv_file = out_path / "drift_results.csv"
    json_file = out_path / "drift_summary.json"

    # Save CSV Report
    drift_df.to_csv(csv_file, index=False)

    # Compile JSON Summary
    total_features = len(drift_df)
    drifted_features = drift_df[drift_df["drift_detected"]]["feature"].tolist()

    summary_payload = {
        "project": "MLflow Experiment Tracking and Data Drift Analysis",
        "method": "Two-Sample Kolmogorov-Smirnov Test (scipy.stats.ks_2samp)",
        "alpha_threshold": scenario_metadata.get("alpha_threshold", 0.05),
        "total_features_evaluated": total_features,
        "drifted_features_count": len(drifted_features),
        "drifted_features_list": drifted_features,
        "overall_drift_status": "DRIFT_DETECTED" if len(drifted_features) > 0 else "NO_DRIFT",
        "scenario_metadata": scenario_metadata,
        "statistical_interpretation": {
            "null_hypothesis": "Reference and current samples share identical continuous distributions.",
            "rule": "p_value < alpha rejects null hypothesis (evidence of feature drift).",
            "caution": "Data drift indicates covariate shift; it does NOT automatically imply concept drift."
        },
        "feature_details": drift_df.to_dict(orient="records")
    }

    with open(json_file, "w", encoding="utf-8") as f:
        json.dump(summary_payload, f, indent=4)

    return {
        "csv_path": str(csv_file),
        "json_path": str(json_file)
    }


def generate_drift_visualizations(
    reference_df: pd.DataFrame,
    current_df: pd.DataFrame,
    drift_df: pd.DataFrame,
    output_dir: str = "artifacts"
) -> Dict[str, str]:
    """
    Produce high-quality visualizations illustrating data drift.

    1. drift_distribution.png: 2x2 comparison histograms with KDE showing
       reference vs current distributions per feature.
    2. feature_drift.png: Bar charts showing KS statistics and p-values against alpha.

    Args:
        reference_df: Baseline reference data.
        current_df: Current monitoring data.
        drift_df: Summary DataFrame with test metrics.
        output_dir: Target folder for saving PNG files.

    Returns:
        Dictionary of created image paths.
    """
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    dist_plot_file = out_path / "drift_distribution.png"
    stat_plot_file = out_path / "feature_drift.png"

    features = list(drift_df["feature"])

    # -------------------------------------------------------------
    # Plot 1: Feature Distribution Comparison (2x2 Grid)
    # -------------------------------------------------------------
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig, axes = plt.subplots(nrows=2, ncols=2, figsize=(14, 10))
    axes = axes.flatten()

    for idx, feature in enumerate(features):
        ax = axes[idx]
        ref_vals = reference_df[feature]
        curr_vals = current_df[feature]

        row = drift_df[drift_df["feature"] == feature].iloc[0]
        drift_detected = row["drift_detected"]
        p_val = row["p_value"]
        ks_stat = row["ks_statistic"]

        # Histograms
        ax.hist(ref_vals, bins=15, alpha=0.55, color="#1f77b4", label="Reference Data", density=True, edgecolor="#0d47a1")
        ax.hist(curr_vals, bins=15, alpha=0.55, color="#d62728", label="Current (Shifted) Data", density=True, edgecolor="#b71c1c")

        # Title & Badges
        status_text = "DRIFT DETECTED" if drift_detected else "NO DRIFT"
        badge_color = "#ffebee" if drift_detected else "#e8f5e9"
        text_color = "#c62828" if drift_detected else "#2e7d32"

        ax.set_title(f"{feature}\nKS Stat = {ks_stat:.4f} | p-value = {p_val:.4e}", fontsize=11, fontweight="bold")
        ax.set_xlabel("Feature Value", fontsize=10)
        ax.set_ylabel("Probability Density", fontsize=10)
        ax.legend(loc="upper right", frameon=True, fontsize=9)

        # Inset text box showing drift status
        ax.text(
            0.05, 0.90, status_text,
            transform=ax.transAxes,
            fontsize=9,
            fontweight="bold",
            color=text_color,
            bbox=dict(boxstyle="round,pad=0.3", facecolor=badge_color, edgecolor=text_color, linewidth=1)
        )

    plt.suptitle("Iris Feature Distribution Comparison (Reference vs. Current)", fontsize=15, fontweight="bold", y=0.99)
    plt.tight_layout()
    plt.savefig(dist_plot_file, dpi=300, bbox_inches="tight")
    plt.close(fig)

    # -------------------------------------------------------------
    # Plot 2: KS Statistic & P-Value Metrics Bar Chart
    # -------------------------------------------------------------
    fig, (ax1, ax2) = plt.subplots(nrows=1, ncols=2, figsize=(14, 5))

    y_pos = np.arange(len(features))
    colors = ["#d62728" if d else "#2ca02c" for d in drift_df["drift_detected"]]

    # Subplot 1: KS Statistic
    ax1.barh(y_pos, drift_df["ks_statistic"], color=colors, alpha=0.85, edgecolor="black")
    ax1.set_yticks(y_pos)
    ax1.set_yticklabels(features, fontsize=10)
    ax1.set_xlabel("Kolmogorov-Smirnov Statistic (D)", fontsize=11, fontweight="bold")
    ax1.set_title("KS Test Statistic per Feature (Higher = Greater Shift)", fontsize=12, fontweight="bold")
    ax1.set_xlim(0, 1.05)
    for i, v in enumerate(drift_df["ks_statistic"]):
        ax1.text(v + 0.02, i, f"{v:.4f}", va="center", fontsize=9, fontweight="bold")

    # Subplot 2: p-value vs Alpha Threshold
    ax2.barh(y_pos, drift_df["p_value"], color=colors, alpha=0.85, edgecolor="black")
    ax2.set_yticks(y_pos)
    ax2.set_yticklabels(features, fontsize=10)
    ax2.axvline(x=0.05, color="red", linestyle="--", linewidth=1.5, label=r"Threshold $\alpha = 0.05$")
    ax2.set_xlabel("p-value", fontsize=11, fontweight="bold")
    ax2.set_title("Statistical Significance p-value (p < 0.05 => Drift)", fontsize=12, fontweight="bold")
    ax2.legend(loc="lower right", frameon=True)
    for i, v in enumerate(drift_df["p_value"]):
        ax2.text(v + 0.01 if v < 0.8 else v - 0.15, i, f"{v:.4f}", va="center", fontsize=9, fontweight="bold")

    plt.suptitle("Statistical Data Drift Evaluation Metrics", fontsize=14, fontweight="bold", y=1.02)
    plt.tight_layout()
    plt.savefig(stat_plot_file, dpi=300, bbox_inches="tight")
    plt.close(fig)

    return {
        "distribution_plot_path": str(dist_plot_file),
        "metrics_plot_path": str(stat_plot_file)
    }
